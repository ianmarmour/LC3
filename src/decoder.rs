//! LC3 decoder (section 3.4).

mod plc;

use crate::bitstream::Reader;
use crate::config::{
    Bandwidth, Config, MAX_FRAME_BYTES, MAX_FRAME_SAMPLES, MAX_SPECTRAL_LINES, MIN_FRAME_BYTES,
};
use crate::error::Error;
use crate::ltpf::{self, Pitch};
use crate::sample::{MAX_SCALED, MIN_SCALED, Sample};
use crate::spectrum::{self, GAIN_INDEX_BITS, LsbMode, NOISE_LEVEL_BITS};
use crate::tns::Tns;
use crate::{mdct, sns};
use plc::Concealment;

/// Outcome of the decoding of a frame.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum FrameStatus {
    /// The frame has been decoded.
    Decoded,
    /// The frame was lost or a bit error has been detected in its payload:
    /// the output has been generated by the packet loss concealment.
    Concealed,
}

/// LC3 decoder of a single audio channel.
///
/// Multi-channel audio is decoded with one decoder per channel. The decoder
/// keeps state from frame to frame, so the frames of a channel must be
/// decoded in order with the same decoder, lost frames included.
#[derive(Clone)]
pub struct Decoder {
    /// Configuration of the decoder.
    config: Config,
    /// Overlap-add memory of the MDCT synthesis.
    overlap: [f32; MAX_FRAME_SAMPLES],
    /// Long term postfilter.
    ltpf: ltpf::Synthesis,
    /// Packet loss concealment.
    plc: Concealment,
    /// Scratch buffers of the MDCT.
    mdct: mdct::Scratch,
    /// Spectrum of the current frame.
    spectrum: [f32; MAX_FRAME_SAMPLES],
    /// Reconstructed signal of the current frame, in the 16 bits range.
    output: [f32; MAX_FRAME_SAMPLES],
    /// Quantized spectrum of the current frame.
    quantized: [i32; MAX_SPECTRAL_LINES],
    /// Escape levels of the 2-tuples of the current frame, for the residual
    /// data of the [`LsbMode::Truncation`] mode.
    levels: [u8; MAX_SPECTRAL_LINES],
    /// Residual bits of the current frame.
    residual: [u8; MAX_SPECTRAL_LINES],
}

impl Decoder {
    /// New decoder for a configuration.
    pub const fn new(config: Config) -> Self {
        Self {
            config,
            overlap: [0.0; MAX_FRAME_SAMPLES],
            ltpf: ltpf::Synthesis::new(),
            plc: Concealment::new(),
            mdct: mdct::Scratch::new(),
            spectrum: [0.0; MAX_FRAME_SAMPLES],
            output: [0.0; MAX_FRAME_SAMPLES],
            quantized: [0; MAX_SPECTRAL_LINES],
            levels: [0; MAX_SPECTRAL_LINES],
            residual: [0; MAX_SPECTRAL_LINES],
        }
    }

    /// Configuration of the decoder.
    pub const fn config(&self) -> &Config {
        &self.config
    }

    /// Decodes a frame into the [`Config::frame_samples`] samples of `pcm`.
    ///
    /// `frame` is `None` for a lost frame, or a frame flagged as corrupted by
    /// the transport: the output is then concealed. It is also concealed when
    /// a bit error is detected in the frame.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidFrameSize`] when the length of `frame` is out of range,
    /// [`Error::InvalidPcmLength`] when `pcm` holds fewer samples than a
    /// frame. The decoder state is unchanged on error.
    pub fn decode<S: Sample>(
        &mut self,
        frame: Option<&[u8]>,
        pcm: &mut [S],
    ) -> Result<FrameStatus, Error> {
        self.decode_interleaved(frame, pcm, 1)
    }

    /// Decodes a frame into a channel of interleaved samples: the samples of
    /// the channel are written to `pcm` with a step of `stride`, the number
    /// of interleaved channels, the first sample being `pcm[0]`.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidFrameSize`] when the length of `frame` is out of range,
    /// [`Error::InvalidPcmLength`] when `stride` is zero or `pcm` holds fewer
    /// samples than a frame. The decoder state is unchanged on error.
    pub fn decode_interleaved<S: Sample>(
        &mut self,
        frame: Option<&[u8]>,
        pcm: &mut [S],
        stride: usize,
    ) -> Result<FrameStatus, Error> {
        let samples = self.config.frame_samples();
        if frame.is_some_and(|f| !(MIN_FRAME_BYTES..=MAX_FRAME_BYTES).contains(&f.len())) {
            return Err(Error::InvalidFrameSize);
        }
        if stride == 0 || pcm.len() < (samples - 1) * stride + 1 {
            return Err(Error::InvalidPcmLength);
        }

        let status = self.decode_frame(frame);

        // Output signal scaling and rounding (section 3.4.10)
        for (s, &x) in pcm.iter_mut().step_by(stride).zip(&self.output[..samples]) {
            *s = S::from_scaled(x.clamp(MIN_SCALED, MAX_SCALED));
        }
        Ok(status)
    }

    /// Decodes a frame, or conceals it, into the output buffer.
    fn decode_frame(&mut self, frame: Option<&[u8]>) -> FrameStatus {
        let config = self.config;
        let samples = config.frame_samples();
        let lines = config.spectral_lines();

        let decoded = frame.and_then(|bytes| Some((self.decode_spectrum(bytes)?, bytes.len())));
        let (status, pitch, nbytes) = match decoded {
            Some((pitch, nbytes)) => {
                self.plc.save(&self.spectrum[..lines]);
                (FrameStatus::Decoded, pitch, nbytes)
            }
            None => {
                self.plc.conceal(&mut self.spectrum[..lines]);
                (FrameStatus::Concealed, None, MIN_FRAME_BYTES)
            }
        };
        self.spectrum[lines..samples].fill(0.0);

        // Low delay MDCT synthesis (section 3.4.8)
        let history = samples - config.mdct_zeros();
        mdct::inverse(
            &config,
            &self.spectrum[..samples],
            &mut self.overlap[..history],
            &mut self.output[..samples],
            &mut self.mdct,
        );

        // Long term postfilter (section 3.4.9)
        let active_pitch = pitch.filter(|p| p.active);
        self.ltpf
            .run(&config, active_pitch, nbytes, &mut self.output[..samples]);
        status
    }

    /// Bitstream decoding and spectrum reconstruction, up to the spectral
    /// noise shaping (sections 3.4.2 to 3.4.7). Returns the pitch of the
    /// frame, or `None` (the outer option) when a bit error is detected.
    fn decode_spectrum(&mut self, bytes: &[u8]) -> Option<Option<Pitch>> {
        let config = self.config;
        let nbytes = bytes.len();
        let nbits = 8 * nbytes as i32;
        let lines = config.spectral_lines();
        let mut r = Reader::new(bytes);

        // Side information (section 3.4.2.3)
        let bw = Bandwidth::from_index(r.read_uint(config.bandwidth_bits()) as usize)
            .filter(|bw| bw.index() <= config.max_bandwidth().index())?;
        let lastnz = 2 * (r.read_uint(config.lastnz_bits()) as usize + 1);
        if lastnz > lines {
            return None;
        }
        let lsb_mode = LsbMode::from_bit(r.read_bit());
        let gain_index = r.read_uint(GAIN_INDEX_BITS) as i32;
        let mut tns = Tns::read_flags(&config, bw, nbytes, &mut r);
        let pitch_present = r.read_bit() == 1;
        let sns_indices = sns::read(&mut r)?;
        let pitch = ltpf::read(&mut r, pitch_present);
        let noise_level = r.read_uint(NOISE_LEVEL_BITS);

        // Arithmetic coded data (section 3.4.2.5)
        r.ac_start();
        tns.read_coefficients(&mut r)?;
        let xq = &mut self.quantized[..lines];
        spectrum::decode(
            &config, nbytes, &mut r, lastnz, lsb_mode, xq, &mut self.levels,
        )?;

        // Residual data (section 3.4.2.6)
        let residual_bits = nbits - (r.nbits_side() + r.nbits_ari());
        if residual_bits < 0 {
            return None;
        }
        let residual = match lsb_mode {
            LsbMode::Truncation => {
                spectrum::decode_lsb_residual(&mut r, residual_bits, lastnz, &self.levels, xq);
                &[][..]
            }
            LsbMode::Refinement => {
                let count = spectrum::read_residual(&mut r, residual_bits, xq, &mut self.residual);
                &self.residual[..count]
            }
        };

        // Residual decoding (section 3.4.3) and noise filling (section 3.4.4)
        let x = &mut self.spectrum[..lines];
        for (v, &q) in x.iter_mut().zip(xq.iter()) {
            *v = q as f32;
        }
        spectrum::apply_residual(x, residual);
        if !spectrum::is_zero_frame(lastnz, xq, gain_index, noise_level) {
            let seed = spectrum::noise_seed(xq);
            spectrum::noise_fill(&config, bw, noise_level, seed, xq, x);
        }

        // Global gain (section 3.4.5)
        let gain = spectrum::global_gain(gain_index, spectrum::global_gain_offset(&config, nbytes));
        for v in x.iter_mut() {
            *v *= gain;
        }

        // TNS decoder (section 3.4.6)
        tns.filter_synthesis(x);

        // SNS decoder (section 3.4.7)
        let scfq = sns::dequantize(&sns_indices);
        sns::shape(&config, &scfq, sns::Shaping::Synthesis, x);

        Some(pitch)
    }
}

#[cfg(test)]
mod tests {
    use super::{Decoder, FrameStatus};
    use crate::config::{Config, FrameDuration, MIN_FRAME_BYTES, SampleRate};
    use crate::error::Error;

    const CONFIG: Config = Config::new(SampleRate::Hz48000, FrameDuration::Ms10);

    #[test]
    fn rejects_invalid_arguments() {
        let mut decoder = Decoder::new(CONFIG);
        let mut pcm = [0i16; 480];
        let short = [0u8; MIN_FRAME_BYTES - 1];
        assert_eq!(
            decoder.decode(Some(&short), &mut pcm),
            Err(Error::InvalidFrameSize)
        );
        assert_eq!(
            decoder.decode(None, &mut pcm[..479]),
            Err(Error::InvalidPcmLength)
        );
        assert_eq!(
            decoder.decode_interleaved(None, &mut pcm, 0),
            Err(Error::InvalidPcmLength)
        );
    }

    #[test]
    fn conceals_lost_frames() {
        let mut decoder = Decoder::new(CONFIG);
        let mut pcm = [1i16; 480];
        assert_eq!(decoder.decode(None, &mut pcm), Ok(FrameStatus::Concealed));
        assert_eq!(pcm, [0; 480]);
    }

    #[test]
    fn conceals_frames_with_bit_errors() {
        // An out of range bandwidth (7 at 48 kHz) is detected as a bit error.
        let mut decoder = Decoder::new(CONFIG);
        let mut pcm = [0i16; 480];
        assert_eq!(
            decoder.decode(Some(&[0xff; 100]), &mut pcm),
            Ok(FrameStatus::Concealed)
        );
    }

    #[test]
    fn decodes_into_interleaved_channels() {
        let mut decoder = Decoder::new(CONFIG);
        let mut pcm = [7i16; 960];
        decoder.decode_interleaved(None, &mut pcm[1..], 2).unwrap();
        assert!(pcm.chunks(2).all(|pair| pair == [7, 0]));
    }
}
