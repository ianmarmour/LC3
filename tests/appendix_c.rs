//! End-to-end tests against the examples of appendix C of the specification:
//! two frames encoded at 16 kHz and 32 kbit/s, for both frame durations.

#![allow(clippy::excessive_precision, clippy::unreadable_literal)]

use lc3::{Config, Decoder, Encoder, FrameDuration, FrameStatus, SampleRate};

/// Largest difference between the decoded samples and those of appendix C,
/// in the 16 bits range: the reference decoder computes in double precision.
const OUTPUT_TOLERANCE: f64 = 0.02;

/// Scale of the 16 bits range relative to floating point samples.
const SCALE_16_BITS: f64 = 32_768.0;

/// A frame of an example.
struct Frame {
    /// Input samples.
    input: &'static [i16],
    /// Encoded frame.
    encoded: &'static [u8],
    /// Decoded samples, before rounding.
    output: &'static [f64],
}

/// An example: two consecutive frames of a configuration.
struct Example {
    /// Configuration of the codec.
    config: Config,
    /// The frames.
    frames: [Frame; 2],
}

/// The examples, at 10 ms and 7.5 ms.
const EXAMPLES: [Example; 2] = [
    Example {
        config: Config::new(SampleRate::Hz16000, FrameDuration::Ms10),
        frames: [
            Frame {
                input: &INPUT_10MS_1,
                encoded: &FRAME_10MS_1,
                output: &OUTPUT_10MS_1,
            },
            Frame {
                input: &INPUT_10MS_2,
                encoded: &FRAME_10MS_2,
                output: &OUTPUT_10MS_2,
            },
        ],
    },
    Example {
        config: Config::new(SampleRate::Hz16000, FrameDuration::Ms7_5),
        frames: [
            Frame {
                input: &INPUT_7M5_1,
                encoded: &FRAME_7M5_1,
                output: &OUTPUT_7M5_1,
            },
            Frame {
                input: &INPUT_7M5_2,
                encoded: &FRAME_7M5_2,
                output: &OUTPUT_7M5_2,
            },
        ],
    },
];

#[test]
fn encoder_output_matches() {
    for Example { config, frames } in &EXAMPLES {
        let mut encoder = Encoder::new(*config);
        for (i, expected) in frames.iter().enumerate() {
            let mut frame = vec![0; expected.encoded.len()];
            encoder.encode(expected.input, &mut frame).unwrap();
            assert_eq!(frame, expected.encoded, "{config:?}, frame {}", i + 1);
        }
    }
}

#[test]
fn decoder_output_matches() {
    for Example { config, frames } in &EXAMPLES {
        let mut decoder = Decoder::new(*config);
        for (i, expected) in frames.iter().enumerate() {
            let mut output = vec![0.0f32; config.frame_samples()];
            let status = decoder.decode(Some(expected.encoded), &mut output).unwrap();
            assert_eq!(status, FrameStatus::Decoded);
            for (n, (&got, &want)) in output.iter().zip(expected.output).enumerate() {
                let got = f64::from(got) * SCALE_16_BITS;
                assert!(
                    (got - want).abs() <= OUTPUT_TOLERANCE,
                    "{config:?}, frame {}, sample {n}: got {got}, want {want}",
                    i + 1
                );
            }
        }
    }
}

